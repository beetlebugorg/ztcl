//! The slots of the four stubs tables of Tcl 8.6, from the Unix headers.
//! `tools/cext/stubs.py` writes this file. A null slot is reserved.
//! Each public slot has the area of its group of the build-out.
//!
//! SPDX-License-Identifier: BSD-2-Clause

pub const Area = enum {
    memory,
    threads,
    errors,
    lists_and_dicts,
    zlib,
    events,
    channels,
    filesystem,
    strings_and_encodings,
    namespaces,
    packages,
    scripts_and_results,
    variables,
    hash_tables,
    interps_and_commands,
    objects,

    pub fn label(a: Area) []const u8 {
        return switch (a) {
            .memory => "memory",
            .threads => "threads",
            .errors => "errors",
            .lists_and_dicts => "lists and dicts",
            .zlib => "zlib",
            .events => "events",
            .channels => "channels",
            .filesystem => "filesystem",
            .strings_and_encodings => "strings and encodings",
            .namespaces => "namespaces",
            .packages => "packages",
            .scripts_and_results => "scripts and results",
            .variables => "variables",
            .hash_tables => "hash tables",
            .interps_and_commands => "interps and commands",
            .objects => "objects",
        };
    }
};

